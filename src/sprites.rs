use crate::game::ItemId;

pub const SPRITE_SIZE: usize = 16;

pub type Sprite = [&'static str; SPRITE_SIZE];

/// Maps a palette letter to RGB; `.` (or anything unknown) is transparent.
pub fn color(code: char) -> Option<(u8, u8, u8)> {
    Some(match code {
        'k' => (20, 20, 28),
        'w' => (242, 242, 242),
        'g' => (160, 160, 170),
        'd' => (78, 78, 90),
        'r' => (225, 55, 60),
        'p' => (242, 160, 185),
        's' => (240, 198, 160),
        'S' => (196, 145, 110),
        'y' => (250, 212, 60),
        'o' => (240, 140, 40),
        'b' => (150, 95, 50),
        'B' => (70, 40, 20),
        'j' => (95, 200, 145),
        'J' => (35, 115, 85),
        'c' => (130, 210, 235),
        'C' => (45, 105, 215),
        'n' => (25, 35, 85),
        'm' => (225, 80, 215),
        'M' => (115, 40, 160),
        'l' => (200, 245, 255),
        _ => return None,
    })
}

